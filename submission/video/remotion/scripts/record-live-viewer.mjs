// Native capture of the verified public viewer only; never controls gameplay.
import {spawn} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../../../',import.meta.url));
const dir=resolve(root,'.local/live-broadcast');
const w=JSON.parse(await readFile(resolve(dir,'viewer-window.json'),'utf8'));
const broadcast=JSON.parse(await readFile(resolve(root,'submission/video/stream-setup/twitch-status.json'),'utf8'));
if(!broadcast.is_live)throw new Error('A verified active broadcast is required');
const started=new Date();const stamp=started.toISOString().replace(/[:.]/g,'-');
const file=resolve(dir,`twitch-viewer-${stamp}.mov`);
const child=spawn('screencapture',['-v','-V','600','-l',String(w.id),'-x',file],{detached:true,stdio:'ignore'});
await new Promise((ok,fail)=>{child.once('spawn',ok);child.once('error',fail);});child.unref();
const record={started_at:started.toISOString(),duration_limit_seconds:600,pid:child.pid,window_id:w.id,file,broadcast_id:broadcast.broadcast_id,broadcast_started_at:broadcast.started_at,evidence_kind:'ACTUAL_NATIVE_PUBLIC_TWITCH_VIEWER_CAPTURE',limits:['Raw footage is private until cropped and reviewed.','No chat, approval or gameplay is generated by this recorder.','Broadcast timing includes real stream latency.']};
await writeFile(resolve(dir,'recording.json'),JSON.stringify(record,null,2)+'\n');
console.log(JSON.stringify({recording_started:true,started_at:record.started_at,duration_limit_seconds:600,window_id:w.id}));
